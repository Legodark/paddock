"""Prepare the archived manufacturer artwork for the web; no downloads.

Requires ImageMagick 7 (magick). Outputs are committed so normal builds do not
need an image processor. The frozen canonical IDs are never renumbered.
"""
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'padook/Frontend/assets/images/marcas'
DESTINATION = ROOT / 'web/public/brand-logos'
REPORT = ROOT / 'docs/evidence/ux/brand-assets.json'
RECIPE = ['-trim', '+repage', '-resize', '96x96>', '-strip', '-depth', '8',
          '-quality', '80', '-define', 'webp:alpha-quality=100', '-define', 'webp:method=6']


def sha(data):
    return hashlib.sha256(data).hexdigest()


def main():
    contract = json.loads((ROOT / 'experiments/model-contract/feature-contract.json').read_text())
    # There are two Lynk & Co archives. Use the correctly proportioned wordmark;
    # lotis.png and vauxhall.png do not correspond to a separate canonical brand.
    exceptions = {'38': 'lynkco'}
    DESTINATION.mkdir(parents=True, exist_ok=True)
    previous = json.loads(REPORT.read_text())['assets'] if REPORT.exists() else []
    manifest, mapping = [], {}
    version = subprocess.check_output(['magick', '-version'], text=True).splitlines()[0]
    for brand_id, name in contract['categories']['brands'].items():
        stem = exceptions.get(brand_id, name.lower().replace(' ', '_').replace('-', '_'))
        source = SOURCE / (stem + '.png')
        original = source.read_bytes()
        converted = subprocess.check_output(['magick', str(source), *RECIPE, 'webp:-'])
        filename = f'{stem}.{sha(converted)[:12]}.webp'
        (DESTINATION / filename).write_bytes(converted)
        width, height = map(int, subprocess.check_output(
            ['magick', 'identify', '-format', '%w %h', str(DESTINATION / filename)], text=True).split())
        if not 0 < width <= 96 or not 0 < height <= 96:
            raise ValueError('Unexpected logo dimensions: ' + stem)
        mapping[brand_id] = {'brand': name, 'src': '/brand-logos/' + filename}
        manifest.append({'id': brand_id, 'brand': name,
                         'source': str(source.relative_to(ROOT)),
                         'source_sha256': sha(original), 'source_bytes': len(original),
                         'output': str((DESTINATION / filename).relative_to(ROOT)),
                         'sha256': sha(converted), 'bytes': len(converted),
                         'width': width, 'height': height})
    (ROOT / 'web/src/brand-logos.ts').write_text(
        '// Generated by tools/prepare_brand_logos.py from the frozen canonical contract.\n'
        'export const BRAND_LOGOS: Readonly<Record<string, { brand: string; src: string }>> = '
        + json.dumps(mapping, ensure_ascii=False, indent=2) + ';\n')
    report = {'processor': version, 'recipe': RECIPE, 'canonical_brands': len(manifest),
              'original_files_unchanged': True,
              'source_bytes': sum(item['source_bytes'] for item in manifest),
              'output_bytes': sum(item['bytes'] for item in manifest),
              'scope': 'Local archived assets only. No Firebase, scraping, or external image requests.',
              'assets': manifest}
    REPORT.write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')
    current_outputs = {item['output'] for item in manifest}
    for old in previous:
        path = ROOT / old['output']
        if old['output'] not in current_outputs and path.parent == DESTINATION:
            path.unlink(missing_ok=True)
    print(json.dumps({key: report[key] for key in ['canonical_brands', 'source_bytes', 'output_bytes']}, indent=2))


if __name__ == '__main__':
    main()
